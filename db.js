function seed() {
  const { c } = db.prepare('SELECT COUNT(*) AS c FROM services').get();
  if (c === 0) {
    const insert = db.prepare(`
      INSERT INTO services (slug, title, category, price, price_note, duration, summary, description, includes, image, warranty, sort)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);
    for (const s of SEED_SERVICES) {
      insert.run(
        s.slug, s.title, s.category, s.price, s.price_note, s.duration,
        s.summary, s.description, JSON.stringify(s.includes), s.image, s.warranty, s.sort
      );
    }
  }

  const { r } = db.prepare('SELECT COUNT(*) AS r FROM reviews').get();
  if (r === 0) {
    const insert = db.prepare('INSERT INTO reviews (author, car, text, rating) VALUES (?, ?, ?, ?)');
    for (const rev of SEED_REVIEWS) insert.run(rev.author, rev.car, rev.text, rev.rating);
  }
}

